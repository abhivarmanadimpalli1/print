export type ColorMode = 'bw' | 'color';
export type PrintSides = 'single' | 'duplex';
export type PaperSize = 'A4' | 'A3' | 'Letter' | 'Legal';
export type PageRangeType = 'all' | 'custom';
export type PaymentChoice = 'counter' | 'online';
export type PaymentStatus = 'pending' | 'paid' | 'pay_at_counter';

export type OrderStatus =
  | 'new'
  | 'review'
  | 'approved'
  | 'printing'
  | 'ready'
  | 'completed'
  | 'cancelled';

export interface PaperSizeOption {
  id: PaperSize;
  name: string;
  multiplier: number;
}

export interface ShopPricing {
  bwPerPage: number;
  colorPerPage: number;
  duplexRateRatio: number;
  paperSizes: PaperSizeOption[];
}

export interface Shop {
  id: string;                     // unique slug or ID, e.g. "campus-prints", "sri-krishna-xerox"
  slug: string;                   // unique URL path slug
  name: string;
  tagline: string;
  location: string;
  phone: string;
  isOpen: boolean;
  openingHours: string;
  pricing: ShopPricing;
  acceptedPaymentModes: PaymentChoice[];
  retentionMinutes: number;
  qrCodeUrl: string;
  // Multi-Store & SaaS Owner Management:
  ownerName?: string;             // Bookstore owner's name
  ownerPhone?: string;            // WhatsApp contact for billing & support
  loginId?: string;               // Bookstore login ID (e.g. "srikrishna")
  passwordHash?: string;          // Password or 4-digit PIN (e.g. "7845")
  monthlySubscriptionFee?: number;// e.g. ₹499/month paid to Abhinav
  subscriptionStatus?: 'active' | 'trial' | 'past_due' | 'suspended';
  subscriptionRenewDate?: string; // ISO date string
  createdAt?: string;             // ISO date string
}

export interface CityPlatformMetrics {
  totalShops: number;
  activeSubscriptions: number;
  monthlyRecurringRevenue: number; // Abhinav's monthly SaaS income
  totalCityOrders: number;
  totalCityGrossSales: number;     // Gross sales generated by all bookstores
  totalCityPagesPrinted: number;
}

export interface PrintJobConfig {
  copies: number;
  colorMode: ColorMode;
  paperSize: PaperSize;
  sides: PrintSides;
  pageRangeType: PageRangeType;
  customPageRange: string;
  selectedPageCount: number;
  sheetsNeeded: number;
  unitPricePerPage: number;
  subtotal: number;
  isRevisedQuote?: boolean;
  revisedAmount?: number;
}

export interface StatusHistoryEntry {
  status: OrderStatus;
  timestamp: string;
  note?: string;
}

export interface OrderAttachment {
  name: string;
  size: number;
  storagePath?: string;
}

export interface Order {
  id: string;
  orderNumber: number;
  shopId: string;
  customerName: string;
  customerPhone: string;
  customerNotes?: string;
  fileName: string;
  fileSize: number;
  fileDataUrl?: string;      // local base64 data URL
  fileDownloadUrl?: string;  // cloud URL to the REAL uploaded PDF file
  attachments?: OrderAttachment[];
  detectedPageCount: number;
  config: PrintJobConfig;
  paymentMode: PaymentChoice;
  paymentStatus: PaymentStatus;
  status: OrderStatus;
  statusHistory: StatusHistoryEntry[];
  rejectionReason?: string;
  clarificationNote?: string;
  createdAt: string;
  updatedAt: string;
  // 10-Minute Auto-Purge Lifecycle
  downloadedAt?: string;
  printedAt?: string;
  purgeAt?: string;
  isPurged?: boolean;
  purgedAt?: string;
}
